export type SightingKind = 'confirmed' | 'rumored' | 'event'

export interface Sighting {
  id: string
  kind: SightingKind
  title: string
  city: string
  country: string
  lat: number
  lng: number
  time: string
  blurb: string
  /** Map pin fill — stable “random” color per sighting */
  pinColor: string
}

/** Deterministic vivid color from an id string. */
export function colorFromId(id: string): string {
  let h = 2166136261
  for (let i = 0; i < id.length; i++) {
    h ^= id.charCodeAt(i)
    h = Math.imul(h, 16777619)
  }
  const hue = (h >>> 0) % 360
  const sat = 62 + ((h >>> 0) % 20)
  const lit = 48 + (((h >>> 8) % 14))
  return `hsl(${hue} ${sat}% ${lit}%)`
}

